export const cityFor = (country, seed) => {
  const list = CITIES[country];
  if (!list) return null;
  const total = list.reduce((s, c) => s + c[3], 0);
  let at = ((Math.imul(seed + 1, 2654435761) >>> 0) / 2 ** 32) * total;
  for (const [city, lat, lon, w] of list) {
    at -= w;
    if (at < 0) return { city, lat, lon };
  }
  return null;
};
