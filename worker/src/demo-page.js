/**
 * The showcase page served at `/`.
 *
 * The home view lists every widget variant as a button on one glass slab;
 * opening one
 * (`/#auto`, `/#invisible`, `/#click`, `/#mascot`, `/#mascot-auto`, `/#bare`,
 * `/#bare-auto`) mounts that variant on its own "stage", solves a real
 * challenge and sends the token to `POST /demo/siteverify` — a
 * same-origin-only route that runs the exact same server-side verification as
 * `/siteverify` with the Worker's secret, so no secret ever reaches the
 * browser. The page logic lives in `demo/app.client.js`, the styles in
 * `demo/page.css`; both are inlined here by wrangler's Text rules.
 *
 * Styling comes from Rakko Design: `vendor/rakko-design/` (generated by
 * `scripts/sync-design.sh`, never edited by hand) provides the tokens, the
 * glass material and the state layer, inlined ahead of the page CSS, and the
 * ripple runtime, served at `/design/*.js` (see `src/widget.js`).
 *
 * The widgets use their own `/demo/challenge` + `/demo/redeem` endpoints
 * (`data-cap-api-endpoint="/demo/"`): those issue demo-scoped tokens, the only
 * kind `/demo/siteverify` accepts. The `window.CAP_CUSTOM_*` variables point
 * the widget's wasm and pako fetches at this origin instead of jsDelivr; they
 * must be set before the widget script loads. Every asset URL carries a
 * `?v=` content hash (`versionedPath` in `src/widget.js`), so after a deploy
 * no browser pairs this page with a widget it cached earlier. The mascot
 * variants need no
 * image URL: the widget's default `<script directory>/mascot/` base resolves
 * to `/mascot/*.webp` on this origin.
 */

