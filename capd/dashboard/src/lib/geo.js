export const countryName = (code) =>
  Object.hasOwn(countryNames, code) ? countryNames[code] : code;

export const flagUrl = (code) =>
  /^[A-Za-z]{2}$/.test(code || "")
    ? new URL(
        `public/assets/flags/${code.toLowerCase()}.svg`,
        document.baseURI,
      ).toString()
    : "";

export const countryFlags = (code) => {
  const src = flagUrl(code);
  if (!src) return "";
  return `<img src="${src}" alt="${code}" class="country-flag" onerror="this.style.display='none'">`;
};

export const countryFlagEmoji = (code) => {
  if (!/^[A-Za-z]{2}$/.test(code || "")) return "";
  const offset = 0x1f1e6;
  return String.fromCodePoint(
    code.charCodeAt(0) - 65 + offset,
    code.charCodeAt(1) - 65 + offset,
  );
};

